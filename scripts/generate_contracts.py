"""Generate offline API documentation and TypeScript domain types without Node tooling."""
from __future__ import annotations

import inspect
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from tenderproof import models
from tenderproof.main import app


def ts(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key, sep in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return sep.join(ts(v) for v in schema[key])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        if not props:
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {ts(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        return "{\n" + "\n".join(f"  {json.dumps(k)}{'' if k in required else '?'}: {ts(v)};" for k, v in props.items()) + "\n}"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generate():
    document = app.openapi()
    schemas = document.setdefault("components", {}).setdefault("schemas", {})
    response_models = {"Position", "SourceSpan", "PageRecord", "Issue", "CostLine", "MatchCandidate", "Run", "Document", "Requirement", "CommercialAdjustment", "ReviewDecision", "ExtractionBatch"}
    for name, cls in inspect.getmembers(models, inspect.isclass):
        if cls is models.Model or not issubclass(cls, models.Model):
            continue
        schema = cls.model_json_schema(ref_template="#/components/schemas/{model}")
        schema.pop("$defs", None)
        # Application response serialization includes defaults as well as supplied fields.
        if name in response_models:
            schema["required"] = list(schema.get("properties", {}))
        schemas[name] = schema
    (ROOT / "docs" / "openapi.json").write_text(json.dumps(document, indent=2, ensure_ascii=False), encoding="utf-8")
    destination = ROOT / "frontend" / "src" / "generated"
    destination.mkdir(parents=True, exist_ok=True)
    content = "// Generated by scripts/generate_contracts.py from the FastAPI/Pydantic schema. Do not edit.\n"
    content += "// Monetary amounts and decimal quantities remain strings.\n\n"
    content += "\n\n".join(f"export type {name} = {ts(schema)};" for name, schema in sorted(schemas.items())) + "\n"
    (destination / "contracts.ts").write_text(content, encoding="utf-8")
    print(f"Generated {len(schemas)} types and docs/openapi.json")


if __name__ == "__main__":
    generate()
